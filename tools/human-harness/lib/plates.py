# Overlap-plate polygons in metres. Copied off docs/models/*/silhouette.svg.
# Front: +X is the figure's right (image right on the plate). +Y up.
# 1 SVG unit = 1 cm. Feet at local y 210, crown of 1.80 m at local y 30.

def _front(pts, ox=70):
    return tuple((round((x - ox) / 100.0, 5), round((210 - y) / 100.0, 5)) for x, y in pts)


def _dancer(pts, ox=75, oy=666):
    # 10 SVG units = 1 metre. Hem point sits on the origin.
    return tuple((round((x - ox) / 10.0, 5), round((oy - y) / 10.0, 5)) for x, y in pts)


