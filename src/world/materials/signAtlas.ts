function bank(script: SignScript): Seg[][] {
  if (script === 'kana') return KANA;
  if (script === 'hangul') return HANGUL;
  if (script === 'hanzi') return HANZI;
  if (script === 'cyrillic') return CYR;
  return DEVA;
}

function pair(i: number, n: number, count: number): number[] {
  const out: number[] = [];
  let k = i % n;
  for (let g = 0; g < count; g++) {
    out.push(k);
    k = (k + 3 + i % 2) % n;
    if (out.includes(k)) k = (k + 1) % n;
  }
  return out;
}

function drawSegs(ctx: CanvasRenderingContext2D, x: number, y: number, w: number, h: number, segs: Seg[]): void {
  ctx.beginPath();
  for (const s of segs) {
    ctx.moveTo(x + s[0] * w, y + s[1] * h);
    ctx.lineTo(x + s[2] * w, y + s[3] * h);
  }
  ctx.stroke();
}

function fitFont(ctx: CanvasRenderingContext2D, text: string, maxW: number, start: number, min: number): number {
  let px = start;
  while (px > min) {
    ctx.font = `700 ${px}px sans-serif`;
    if (ctx.measureText(text).width <= maxW) return px;
    px -= 1;
  }
  ctx.font = `700 ${min}px sans-serif`;
  return min;
}

let texture: CanvasTexture | null = null;

export function getSignAtlas(): CanvasTexture {
  if (texture) return texture;
  const canvas = document.createElement('canvas');
  canvas.width = SIGN_ATLAS_COLS * CELL_W;
  canvas.height = SIGN_ATLAS_ROWS * CELL_H;
  const ctx = canvas.getContext('2d');
  if (!ctx) throw new Error('sign atlas: no 2d context');
  ctx.fillStyle = '#05040a';
  ctx.fillRect(0, 0, canvas.width, canvas.height);
  ctx.lineCap = 'round';
  ctx.lineJoin = 'round';
  ctx.textBaseline = 'middle';

  SIGN_PHRASES.forEach((phrase, i) => {
    const col = i % SIGN_ATLAS_COLS;
    const row = Math.floor(i / SIGN_ATLAS_COLS);
    const x = col * CELL_W;
    const y = row * CELL_H;
    ctx.save();
    ctx.beginPath();
    ctx.rect(x, y, CELL_W, CELL_H);
    ctx.clip();

    if (phrase.paper) {
      ctx.shadowBlur = 0;
      ctx.fillStyle = '#efe2c6';
      ctx.fillRect(x, y, CELL_W, CELL_H);
      ctx.strokeStyle = '#2a2116';
      ctx.lineWidth = 2.2;
      ctx.strokeRect(x + 4, y + 4, CELL_W - 8, CELL_H - 8);
      ctx.lineWidth = 1.2;
      ctx.strokeRect(x + 8, y + 8, CELL_W - 16, CELL_H - 16);
      ctx.fillStyle = '#1c140c';
      fitFont(ctx, phrase.latin, CELL_W - 36, 26, 13);
      ctx.fillText(phrase.latin, x + 16, y + CELL_H / 2 + 1);
      ctx.restore();
      return;
    }

    ctx.fillStyle = '#09070f';
    ctx.fillRect(x, y, CELL_W, CELL_H);
    ctx.shadowColor = '#ffffff';
    ctx.shadowBlur = 6;
    ctx.strokeStyle = '#ffffff';
    ctx.lineWidth = 2.2;
    ctx.strokeRect(x + 3.5, y + 3.5, CELL_W - 7, CELL_H - 7);
    ctx.fillStyle = '#ffffff';

    if (phrase.script === 'latin') {
      const px = fitFont(ctx, phrase.latin, CELL_W - 28, phrase.latin.length > 16 ? 18 : 26, 12);
      ctx.shadowBlur = 8;
      ctx.fillText(phrase.latin, x + 14, y + CELL_H / 2 + 1);
      void px;
    } else {
      const set = bank(phrase.script);
      const count = phrase.script === 'cyrillic' ? 3 : 2;
      const gw = phrase.script === 'cyrillic' ? 20 : 30;
      const gap = 4;
      const ids = pair(i, set.length, count);
      const gh = 42;
      const gy = y + (CELL_H - gh) / 2;
      const gx = x + 10;
      ctx.lineWidth = 2.2;
      if (phrase.script === 'devanagari') {
        ctx.beginPath();
        ctx.moveTo(gx, gy + 1);
        ctx.lineTo(gx + count * gw + (count - 1) * gap, gy + 1);
        ctx.stroke();
      }
      ids.forEach((id, g) => {
        drawSegs(ctx, gx + g * (gw + gap), gy + (phrase.script === 'devanagari' ? 4 : 0), gw, gh - 4, set[id]!);
      });
      const blockW = count * gw + (count - 1) * gap;
      const tx = gx + blockW + 8;
      const maxW = x + CELL_W - 12 - tx;
      fitFont(ctx, phrase.latin, Math.max(40, maxW), 16, 11);
      ctx.shadowBlur = 5;
      ctx.fillText(phrase.latin, tx, y + CELL_H / 2 + 1);
    }
    ctx.restore();
  });

  texture = new CanvasTexture(canvas);
  texture.colorSpace = SRGBColorSpace;
  texture.wrapS = ClampToEdgeWrapping;
  texture.wrapT = ClampToEdgeWrapping;
  texture.magFilter = LinearFilter;
  texture.minFilter = LinearFilter;
  texture.needsUpdate = true;
  return texture;
}
