function glyphsFor(script: SignScript): Seg[][] {
  if (script === 'kana') return KANA;
  if (script === 'hangul') return HANGUL;
  if (script === 'hanzi') return HANZI;
  if (script === 'cyrillic') return CYR;
  return DEVA;
}

/** Two different complete marks. The pair is stable for a cell, not a random pick. */
function pair(script: SignScript, index: number): [Seg[], Seg[]] {
  const set = glyphsFor(script);
  const a = index % set.length;
  let b = (index * 5 + 3) % set.length;
  if (b === a) b = (a + 1) % set.length;
  return [set[a]!, set[b]!];
}

function drawSegs(ctx: CanvasRenderingContext2D, x: number, y: number, w: number, h: number, segs: Seg[]): void {
  ctx.beginPath();
  for (const s of segs) {
    ctx.moveTo(x + s[0] * w, y + s[1] * h);
    ctx.lineTo(x + s[2] * w, y + s[3] * h);
  }
  ctx.stroke();
}

function fitFont(ctx: CanvasRenderingContext2D, text: string, maxW: number, startPx: number): void {
  let px = startPx;
  ctx.font = `700 ${px}px sans-serif`;
  while (px > 9 && ctx.measureText(text).width > maxW) {
    px -= 1;
    ctx.font = `700 ${px}px sans-serif`;
  }
}

/** Paint the sign atlas into `canvas` (sized here). Row 0 is the top, matching CanvasTexture flipY. */
export function paintSignAtlas(canvas: HTMLCanvasElement): void {
  canvas.width = SIGN_ATLAS_COLS * CELL_W;
  canvas.height = SIGN_ATLAS_ROWS * CELL_H;
  const ctx = canvas.getContext('2d');
  if (!ctx) throw new Error('sign atlas: no 2d context');
  ctx.fillStyle = '#05040a';
  ctx.fillRect(0, 0, canvas.width, canvas.height);
  ctx.lineCap = 'round';
  ctx.lineJoin = 'round';
  ctx.textBaseline = 'middle';
  ctx.shadowColor = '#ffffff';

  SIGN_PHRASES.forEach((phrase, i) => {
    const col = i % SIGN_ATLAS_COLS;
    const row = Math.floor(i / SIGN_ATLAS_COLS);
    const x = col * CELL_W;
    const y = row * CELL_H;
    ctx.save();
    ctx.beginPath();
    ctx.rect(x, y, CELL_W, CELL_H);
    ctx.clip();
    ctx.fillStyle = '#09070f';
    ctx.fillRect(x, y, CELL_W, CELL_H);
    ctx.shadowBlur = 7;
    ctx.strokeStyle = '#ffffff';
    ctx.lineWidth = 2.5;
    ctx.strokeRect(x + 3.5, y + 3.5, CELL_W - 7, CELL_H - 7);
    ctx.fillStyle = '#ffffff';
    if (phrase.script === 'latin') {
      fitFont(ctx, phrase.latin, CELL_W - 28, 28);
      ctx.shadowBlur = 10;
      ctx.fillText(phrase.latin, x + 14, y + CELL_H / 2 + 1);
    } else {
      // Two marks, inset from the short edges, so a rotated blade still holds one whole mark.
      const [g0, g1] = pair(phrase.script, i);
      const gw = 46;
      const gh = 46;
      const gy = y + (CELL_H - gh) / 2;
      ctx.lineWidth = 2.6;
      ctx.shadowBlur = 6;
      drawSegs(ctx, x + 8, gy, gw, gh, g0);
      drawSegs(ctx, x + 8 + gw + 6, gy, gw, gh, g1);
      const textX = x + 8 + 2 * (gw + 6);
      fitFont(ctx, phrase.latin, CELL_W - (textX - x) - 12, 16);
      ctx.shadowBlur = 6;
      ctx.fillText(phrase.latin, textX, y + CELL_H / 2 + 1);
    }
    ctx.restore();
  });

}
